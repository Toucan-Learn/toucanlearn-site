// No dependencies or browser. Copy only rules whose leading class/id occurs in
// the page. Keep whole declarations and nested conditions verbatim and in order.
// Full sheets still load afterwards, in their original order: no cascade rewrite.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const openingPages = ['index', 'children', 'adults', 'subjects', 'approach', 'team', 'contact'];
export function openingCSS(html, read) {
  const opening = html.includes('class="homepage"') ? html.slice(0, html.indexOf('<section class="homepage-section team-section"')) : html;
  const names = new Set([...opening.matchAll(/\b(?:class|id)="([^"]*)"/g)].flatMap(match => match[1].split(/\s+/)));
  // Dynamic navigation states need their styles before the first interaction.
  for (const name of ['is-open', 'is-active', 'is-current', 'is-visible']) names.add(name);
  const keep = selector => {
    const first = selector.match(/[.#]([a-zA-Z_-][\w-]*)/);
    return !first || names.has(first[1]);
  };
  const splitSelectors = selector => selector.split(/,(?![^()]*\))/);
  function filter(css) {
    css = css.replace(/\/\*[\s\S]*?\*\//g, '');
    let out = '', start = 0, quote = '', depth = 0, open;
    for (let i = 0; i < css.length; i++) {
      const ch = css[i];
      if (quote) { if (ch === '\\') i++; else if (ch === quote) quote = ''; continue; }
      if (ch === '"' || ch === "'") { quote = ch; continue; }
      if (ch === '{') { if (depth++ === 0) open = i; }
      if (ch !== '}' || --depth !== 0) continue;
      const head = css.slice(start, open).trim(), body = css.slice(open + 1, i);
      start = i + 1;
      if (/^@(media|supports|container|layer)\b/.test(head)) {
        const inner = filter(body); if (inner) out += `${head}{${inner}}\n`;
      } else if (head.startsWith('@') || splitSelectors(head).some(keep)) {
        out += `${head}{${body}}\n`;
      }
    }
    return out;
  }
  return [...html.matchAll(/<link\b[^>]*data-deferred-style[^>]*href="([^"?]+)[^"]*"[^>]*>/g)]
    .map(([, file]) => filter(read(file)).replace(/url\(([^)]*)\)/g, (all, value) => {
      const url = value.trim().replace(/^[\'"]|[\'"]$/g, '');
      return /^(?:[a-z]+:|\/|#)/i.test(url) ? all : `url("/${url}")`;
    })).join('\n');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.join(root, 'assets/css'), { recursive: true });
  for (const page of openingPages) {
    const html = fs.readFileSync(path.join(root, `${page}.html`), 'utf8');
    const css = openingCSS(html, file => fs.readFileSync(path.join(root, file), 'utf8'));
    fs.writeFileSync(path.join(root, `assets/css/opening-${page}.css`), `/* Generated by scripts/build-opening-css.mjs; edit the original sheets. */\n${css}`);
    console.log(`${page}: ${Buffer.byteLength(css)} opening CSS bytes`);
  }
}
